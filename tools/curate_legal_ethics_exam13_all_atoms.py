def validate(data: dict) -> None:
    items = data["items"]
    if data["count"] != len(items):
        raise ValueError("count mismatch")
    per_q = {q: 0 for q in range(1, 41)}
    forbidden = ["甲", "乙", "丙", "丁", " 戊", " 己", " 이 사례", "이 사례는", " 위 사안", "위 사안은"]
    case_person = re.compile(r"(?<![A-Z])[A-D](?![A-Z])")
    for item in items:
        for q in item["ids"]:
            per_q[q] += 1
        texts = [item["rep"], item["why"], item["ref"]]
        for twin in item.get("twins", []):
            texts.extend([twin.get("q", ""), twin.get("why", ""), twin.get("corrected", "")])
        for text in texts:
            if any(token in text for token in forbidden):
                raise ValueError(f"forbidden token in {item['pid']}: {text}")
            if case_person.search(text):
                raise ValueError(f"case person token in {item['pid']}: {text}")
            if "?" in text:
                raise ValueError(f"question mark in {item['pid']}: {text}")
        if not item["rep"].endswith("."):
            raise ValueError(f"representative is not a sentence: {item['pid']}")
        for twin in item.get("twins", []):
            if not twin.get("q", "").endswith("."):
                raise ValueError(f"twin is not a sentence: {item['pid']}")
    short = {q: n for q, n in per_q.items() if n < 4}
    if short:
        raise ValueError(f"too few atoms: {short}")


