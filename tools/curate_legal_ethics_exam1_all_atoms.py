def validate(data):
    bad = []
    forbidden = ["甲", "乙", "丙", "丁", "戊", "己", " 이 사례", "이 사례는", " 위 사안", "위 사안은"]
    per_q: dict[str, int] = {}
    for item in data["items"]:
        per_q[item["sourceQuestionId"]] = per_q.get(item["sourceQuestionId"], 0) + 1
        texts = [item.get("rep", ""), item.get("why", ""), item.get("ref", "")]
        for twin in item.get("twins", []):
            texts.extend([twin.get("q", ""), twin.get("corrected", ""), twin.get("why", "")])
        blob = " ".join(texts)
        if any(token in blob for token in forbidden):
            bad.append((item["pid"], "forbidden token"))
        if re.search(r"(?<![A-Z])[A-D](?![A-Z])", blob):
            bad.append((item["pid"], "case alphabet"))
        if "?" in blob:
            bad.append((item["pid"], "question mark"))
        if not item["rep"].endswith("."):
            bad.append((item["pid"], "rep not sentence"))
        for twin in item.get("twins", []):
            if not twin["q"].endswith("."):
                bad.append((item["pid"], "twin not sentence"))
    counts = {qid: count for qid, count in per_q.items() if count != 4}
    if counts:
        bad.append(("per_question", counts))
    if len(data["items"]) != 160:
        bad.append(("count", len(data["items"])))
    if bad:
        raise SystemExit(f"validation failed: {bad[:30]}")


