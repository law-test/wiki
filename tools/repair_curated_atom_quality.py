def main() -> None:
    payload: dict[str, Any] = json.loads(BANK.read_text(encoding="utf-8"))
    changed = 0
    missing = set(REPAIRS)
    for item in payload.get("items") or []:
        pid = str(item.get("pid") or "")
        repair = REPAIRS.get(pid)
        if not repair:
            continue
        item["rep"] = repair["rep"]
        item["why"] = repair["why"]
        changed += 1
        missing.discard(pid)
    if missing:
        raise SystemExit(f"missing repair pids: {sorted(missing)}")
    BANK.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"curated atom repairs applied: {changed}")


if __name__ == "__main__":
    main()
